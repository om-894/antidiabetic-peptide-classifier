"""
Build the point-by-point response document and the JCIM cover letter.

Both are new documents rather than edits, so python-docx builds them directly.
Items still waiting on information from the authors are left in square brackets
so they are visible on the page rather than quietly missing.
"""

import docx
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

GAP = RGBColor(0xB0, 0x30, 0x00)


def new_doc():
    d = docx.Document()
    s = d.styles["Normal"]
    s.font.name = "Calibri"
    s.font.size = Pt(11)
    for sec in d.sections:
        sec.left_margin = sec.right_margin = Inches(1.0)
        sec.top_margin = sec.bottom_margin = Inches(0.9)
    return d


def para(d, text, bold=False, italic=False, space=6, align=None, size=None):
    p = d.add_paragraph()
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    if size:
        r.font.size = Pt(size)
    p.paragraph_format.space_after = Pt(space)
    if align:
        p.alignment = align
    return p


def gap(d, text):
    p = d.add_paragraph()
    r = p.add_run(text)
    r.font.color.rgb = GAP
    r.bold = True
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.left_indent = Inches(0.25)
    return p


def item(d, n, comment, response):
    p = d.add_paragraph()
    p.add_run(f"{n}. ").bold = True
    r = p.add_run(comment)
    r.italic = True
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.space_before = Pt(10)
    q = d.add_paragraph()
    q.add_run("Response. ").bold = True
    q.add_run(response)
    q.paragraph_format.space_after = Pt(6)
    q.paragraph_format.left_indent = Inches(0.25)


