def cover_letter():
    d = new_doc()
    para(d, "[Date]", space=14)
    para(d, "The Editors", space=0)
    para(d, "Journal of Chemical Information and Modeling", space=14)
    para(d, "Dear Editors,", space=10)

    para(d, "We submit for your consideration “Negative-Class Design Reveals a "
            "Net-Charge Shortcut in Anti-Diabetic Peptide Prediction”, a "
            "methodological study of how bioactive-peptide classification "
            "datasets are built, scored and reported.", space=8)

    para(d, "The contribution is to dataset design and evaluation practice "
            "rather than to the discovery of any particular inhibitor. Holding "
            "the positives, hyperparameters and test set fixed and varying only "
            "the negative class moves discrimination by 0.219 in AUC and the "
            "false-positive rate on held-out proteome fragments from 93.3% to "
            "46.7%, where varying architecture across four learners, including a "
            "650M-parameter protein language model fine-tuned with DoRA, spans a "
            "range that contains a 20-feature amino-acid composition baseline, "
            "and where Bayesian hyperparameter optimisation moves the best tree "
            "learner by 0.011. A six-arm ablation then separates negative-class "
            "composition from the length and charge distributions it carries. "
            "Two arms differing by 0.03 in AUC differ by 54 points in "
            "false-positive rate, and under a family-aware split the "
            "best-scoring arm is the worst-deploying one, so a negative class "
            "selected on test AUC is selected backwards. Matching the negatives "
            "on net charge as well as length drives the residual shortcut to "
            "chance for 0.018 in AUC.", space=8)

    para(d, "DPP-IV and molecular docking enter this work as a physical control "
            "system, not as the object of study. We chose the target because its "
            "active site is crystallographically characterised, because "
            "documented peptide inhibitors are available as positive controls, "
            "and because the site is strongly anionic, which makes it possible "
            "to test whether a sequence classifier and a structure-based score "
            "agree for the right reason. They do not: net charge moves the two "
            "in opposite directions, and three peptides our classifier "
            "confidently rejected score above a documented inhibitor on "
            "electrostatics alone. The consequence is a reporting rule, that a "
            "hybrid screen should report the electrostatic share of every "
            "docking score rather than the total, and it is stated as such. We "
            "make no claim of a validated hit, and the peptides reported are "
            "described throughout as prioritised hypotheses for experimental "
            "follow-up.", space=8)

    para(d, "We are aware that the journal does not consider straightforward "
            "applications of docking to a single target without experimental "
            "validation. We believe this work falls outside that description: no "
            "result rests on the docking, the docking is itself one of the "
            "objects being measured, and its main role is to demonstrate a "
            "failure mode of hybrid in silico workflows that we then give a "
            "remedy for.", space=8)

    para(d, "The paper also reports against the state of the art. BertADP "
            "misclassified 92.4% of 328 Swiss-Prot fragments it had never seen, "
            "and the same failure appears in a deliberately weak control sharing "
            "its negative source, which locates the cause in the data rather "
            "than the architecture. We additionally quantify what our own "
            "partition is worth: near-duplicates inflate our headline AUC by "
            "about 0.046, cluster-level leakage across the cross-validation "
            "folds inflates the out-of-fold calibration by 0.020, and the "
            "positive class carries about 60% of its nominal sample size. All "
            "three are reported in the manuscript.", space=8)

    para(d, "All code, dataset splits, out-of-fold predictions, model weights "
            "and the scripts generating every table are available at [repository "
            "URL], archived at [DOI]. Each new supporting table names the script "
            "that produces it.", space=8)

    para(d, "The manuscript is original, is not under consideration elsewhere, "
            "and both authors have approved this version. We declare no "
            "competing financial interest.", space=14)

    para(d, "Yours sincerely,", space=10)
    para(d, "Manish Chauhan, on behalf of the authors", space=0)
    para(d, "School of Physics, Engineering and Technology, University of York, "
            "Heslington, York YO10 5DD, United Kingdom", space=0)
    para(d, "[email]", space=0)
    return d


